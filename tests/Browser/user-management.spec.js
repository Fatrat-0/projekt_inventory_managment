import { expect, test } from '@playwright/test';
import { randomUUID } from 'node:crypto';

test('admin can review local role edits and use the filter, keyboard menu and responsive settings', async ({ page }) => {
    await page.goto('/login');
    await page.getByLabel('Email', { exact: true }).fill('warehouse-admin@example.test');
    await page.getByLabel('Password', { exact: true }).fill('browser-test-password');
    await page.getByRole('button', { name: 'Log in', exact: true }).click();
    await expect(page).toHaveURL(/\/dashboard$/);
    await page.goto('/users');
    await page.getByLabel('Név vagy e-mail-cím', { exact: true }).fill('browser@example.test');
    await page.getByLabel('Globális szerepkör', { exact: true }).selectOption('worker');
    await page.getByLabel('Állapot', { exact: true }).selectOption('active');
    await page.getByRole('button', { name: 'Szűrés', exact: true }).click();
    await expect(page.locator('[data-user-id]:visible')).toHaveCount(1);

    await page.setViewportSize({ width: 1440, height: 850 });
    await page.getByRole('button', { name: 'Táblázatos nézet', exact: true }).click();
    await page.getByRole('link', { name: /^Név$/ }).click();
    await expect(page).toHaveURL(/sort_by=name/);
    await page.getByRole('button', { name: 'Táblázat oszlopai', exact: true }).click();
    const columns = page.getByRole('dialog', { name: 'Táblázat oszlopai' });
    await columns.getByRole('checkbox', { name: 'E-mail oszlop megjelenítése', exact: true }).uncheck();
    await expect(columns.getByRole('checkbox', { name: 'Állapot oszlop megjelenítése', exact: true })).toBeDisabled();
    await page.keyboard.press('Escape');
    await page.reload();
    await expect(page.locator('[data-listing-table] td[data-listing-column="email"]')).toBeHidden();

    const action = page.locator('[data-user-id]:visible').getByRole('button', { name: /^Műveletek:/ });
    await action.focus();
    await page.keyboard.press('ArrowDown');
    await expect(page.getByRole('menuitem', { name: 'Adatlap', exact: true })).toBeFocused();
    await page.keyboard.press('ArrowDown');
    await page.keyboard.press('Enter');
    await expect(page).toHaveURL(/\/users\/\d+\/edit/);
    const warehouse = page.getByRole('combobox', { name: 'Raktár hozzáadása', exact: true });
    await expect(warehouse).toHaveAttribute('placeholder', 'Keresés raktárnév alapján…');
    await warehouse.fill('Északi');
    await page.getByRole('option', { name: 'Északi tesztraktár', exact: true }).click();
    const north = page.getByRole('group', { name: 'Helyi szerepkörök · Északi tesztraktár' });
    const pickerRole = north.getByRole('checkbox', { name: 'Kitároló', exact: true });
    const receivingRole = north.getByRole('checkbox', { name: 'Átvevő', exact: true });
    const reviewButton = page.getByRole('button', { name: 'Módosítások ellenőrzése' });
    await expect(north.getByRole('checkbox', { name: 'Igénylő', exact: true })).toBeFocused();
    await expect(reviewButton).toBeDisabled();
    await page.keyboard.press('Tab');
    await expect(pickerRole).toBeFocused();
    await page.keyboard.press('Space');
    await page.keyboard.press('Tab');
    await expect(receivingRole).toBeFocused();
    await page.keyboard.press('Space');
    await expect(pickerRole).toBeChecked();
    await expect(receivingRole).toBeChecked();
    const capabilities = page.getByRole('group', { name: 'Együttes helyi jogosultságok · Északi tesztraktár' });
    await expect(capabilities.getByText('Igény benyújtása', { exact: true })).toHaveCount(1);
    await expect(capabilities.getByText('Több szerepkör is megadja').filter({ visible: true })).toHaveCount(2);
    await expect(page.getByText('Mentetlen módosítások.')).toBeVisible();
    for (const width of [320, 375, 768, 1024, 1440]) {
        await page.setViewportSize({ width, height: 850 });
        expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width + 1);
    }
    await reviewButton.click();
    const review = page.getByRole('dialog', { name: 'Fiók mentésének megerősítése' });
    await expect(review).toContainText('Északi tesztraktár · Kitároló, Átvevő');
    await expect(review).toContainText('Hozzáadott szerepkörök');
    await expect(review).toContainText('Új tagság');
    await expect(review).toContainText('Tényleges hozzáférés változása');
    await expect(review).toContainText('Átvétel és betárolás');
    await expect(review).not.toContainText('Igényelbírálás');
    await expect(review).toContainText('korábbi munkamenetei megszűnnek');
    await page.setViewportSize({ width: 320, height: 700 });
    expect(await review.evaluate(element => element.scrollWidth)).toBeLessThanOrEqual(290);
    await review.getByRole('button', { name: 'Mégse' }).click();
    await expect(review).toBeHidden();
    await page.getByRole('button', { name: 'Módosítások ellenőrzése' }).click();
    await review.getByRole('button', { name: 'Mentés megerősítése' }).click();
    await expect(page).toHaveURL(/\/users\/\d+$/);
    await expect(page.getByRole('region', { name: 'Raktári hozzáférések' })).toContainText('Északi tesztraktár');
    await expect(page.getByRole('region', { name: 'Raktári hozzáférések' })).toContainText('Átvevő');
    await expect(page.getByRole('region', { name: 'Raktári hozzáférések' })).toContainText('Kitároló');
    await expect(page.getByRole('link', { name: 'Szerkesztés', exact: true })).toBeVisible();
    await expect(page.getByRole('region', { name: 'Jogosultsági előzmények' })).toContainText('Fiók módosítása');
    await page.getByRole('link', { name: 'Tagságok szerkesztése' }).click();
    await pickerRole.uncheck();
    await reviewButton.click();
    await expect(review).toContainText('Eltávolított szerepkörök');
    await expect(review).toContainText('Megszűnő jogosultság · Kitárolás');
    await expect(review).not.toContainText('Megszűnő tagság');
    await review.getByRole('button', { name: 'Mentés megerősítése' }).click();
    await expect(page).toHaveURL(/\/users\/\d+$/);
    await expect(page.getByRole('region', { name: 'Raktári hozzáférések' })).not.toContainText('Kitároló');
    await page.getByRole('link', { name: 'Tagságok szerkesztése' }).click();
    const removeMembership = page.getByRole('button', { name: 'Tagság eltávolítása · Északi tesztraktár' });
    await removeMembership.focus();
    await page.keyboard.press('Enter');
    await expect(page.getByRole('combobox', { name: 'Raktár hozzáadása' })).toBeFocused();
    await reviewButton.click();
    await expect(review).toContainText('Megszűnő tagság');
    await review.getByRole('button', { name: 'Mentés megerősítése' }).click();
    await expect(page).toHaveURL(/\/users\/\d+$/);
    await expect(page.getByRole('region', { name: 'Raktári hozzáférések' })).not.toContainText('Északi tesztraktár');
});

test('changing an account email asks for the current password without retaining a failed entry', async ({ page }) => {
    await page.goto('/login');
    await page.getByLabel('Email', { exact: true }).fill('warehouse-admin@example.test');
    await page.getByLabel('Password', { exact: true }).fill('browser-test-password');
    await page.getByRole('button', { name: 'Log in', exact: true }).click();
    await page.goto('/profile');
    const email = page.getByLabel('Email', { exact: true });
    const password = page.getByLabel('Jelenlegi jelszó e-mail-cím módosításához', { exact: true });
    await expect(password).toBeHidden();
    await expect(password).toBeDisabled();
    await email.fill('changed@example.test');
    await expect(password).toBeVisible();
    await expect(password).toHaveAttribute('autocomplete', 'current-password');
    await password.fill('incorrect-local-password');
    await email.locator('xpath=ancestor::form').getByRole('button', { name: 'Save', exact: true }).click();
    await expect(page.getByText('Az e-mail-cím módosításához add meg a jelenlegi jelszavadat.')).toBeVisible();
    await expect(email).toHaveValue('changed@example.test');
    await expect(password).toHaveJSProperty('required', true);
    await expect(password).toHaveValue('');
    await email.fill('warehouse-admin@example.test');
    await expect(password).toBeHidden();
});

test('new form compares actual changes and long account cards keep list context at each width', async ({ page }) => {
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto('/login');
    await page.getByLabel('Email', { exact: true }).fill('warehouse-admin@example.test');
    await page.getByLabel('Password', { exact: true }).fill('browser-test-password');
    await page.getByRole('button', { name: 'Log in', exact: true }).click();
    await page.goto('/users/create');
    const dirty = page.getByText('Mentetlen módosítások.', { exact: true });
    const create = page.getByRole('button', { name: 'Felhasználó létrehozása', exact: true });
    const role = page.getByLabel('Globális szerepkör', { exact: true });
    const nameInput = page.getByLabel('Teljes név', { exact: true });
    await expect(create).toBeEnabled();
    await expect(dirty).toBeHidden();
    await role.selectOption('manager');
    await expect(dirty).toBeVisible();
    await expect(page.locator('#account-role-help')).toContainText('felügyelői tagság szükséges');
    await role.selectOption('worker');
    await expect(dirty).toBeHidden();
    await nameInput.fill('Szerkesztés');
    await expect(dirty).toBeVisible();
    await nameInput.clear();
    await expect(dirty).toBeHidden();

    const name = 'HosszúNév'.repeat(22);
    const email = 'local-'+randomUUID()+'@example.test';
    await nameInput.fill(name);
    await page.getByLabel('E-mail-cím', { exact: true }).fill(email);
    const picker = page.getByRole('combobox', { name: 'Raktár hozzáadása', exact: true });
    await picker.fill('Északi');
    await page.getByRole('option', { name: 'Északi tesztraktár', exact: true }).click();
    const north = page.getByRole('group', { name: 'Helyi szerepkörök · Északi tesztraktár' });
    await north.getByRole('checkbox', { name: 'Kitároló', exact: true }).check();
    await north.getByRole('checkbox', { name: 'Átvevő', exact: true }).check();
    await picker.fill('Déli');
    await page.getByRole('option', { name: 'Déli tesztraktár', exact: true }).click();
    await page.getByRole('group', { name: 'Helyi szerepkörök · Déli tesztraktár' }).getByRole('checkbox', { name: 'Kitároló', exact: true }).check();
    await page.getByRole('radio', { name: 'Ideiglenes jelszó' }).check();
    await page.locator('[name=password]').fill('disposable-local-password');
    await page.locator('[name=password_confirmation]').fill('disposable-local-password');
    await create.click();
    await expect(page.getByRole('dialog')).toContainText('Globális szerepkör Raktáros');
    await page.getByRole('dialog').getByRole('button', { name: 'Mentés megerősítése' }).click();
    await expect(page).toHaveURL(/\/users$/);
    const search = page.getByRole('searchbox', { name: 'Név vagy e-mail-cím' });
    await search.fill(email);
    await page.getByRole('button', { name: 'Kártyás nézet', exact: true }).click();
    await page.locator('[data-listing-card-sort] summary').click();
    await page.locator('[data-listing-card-sort]').getByRole('link', { name: /^Név/ }).click();
    await expect(page).toHaveURL(url => url.searchParams.get('search') === email && url.searchParams.get('sort_by') === 'name');
    await expect(page.getByText('1–1 / 1 találat', { exact: true })).toBeVisible();
    const card = page.locator('[data-listing-cards]').getByRole('article');
    await expect(card).toContainText('2 raktár');
    await expect(card).toContainText('Saját jelszó beállítására vár');
    for (const width of [320, 375, 768, 1024, 1440]) {
        await page.setViewportSize({ width, height: 700 });
        expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width + 1);
        await expect(card.getByRole('button', { name: /^Műveletek:/ })).toBeVisible();
    }
    await page.getByRole('link', { name: /Aktív, tagság nélküli munkatársak/ }).click();
    await expect(page).toHaveURL(url => url.searchParams.get('state') === 'unassigned' && !url.searchParams.has('search'));
    await expect(page.getByRole('link', { name: 'Összes szűrő törlése' })).toBeVisible();
    expect(errors).toEqual([]);
});
